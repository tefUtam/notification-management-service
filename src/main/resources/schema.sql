CREATE TABLE IF NOT EXISTS notifications (
    id VARCHAR(36) PRIMARY KEY,
    source_system VARCHAR(120) NOT NULL,
    event_id VARCHAR(200) NOT NULL,
    notification_type VARCHAR(100) NOT NULL,
    severity VARCHAR(20) NOT NULL,
    priority INTEGER NOT NULL,
    subject VARCHAR(200) NOT NULL,
    message CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    scheduled_at TIMESTAMP WITH TIME ZONE,
    expires_at TIMESTAMP WITH TIME ZONE,
    idempotency_key VARCHAR(200),
    payload_hash VARCHAR(64) NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_notification_idempotency
    ON notifications(source_system, idempotency_key);
CREATE INDEX IF NOT EXISTS ix_notification_dedup
    ON notifications(source_system, event_id, notification_type, created_at);

CREATE TABLE IF NOT EXISTS deliveries (
    id VARCHAR(36) PRIMARY KEY,
    notification_id VARCHAR(36) NOT NULL REFERENCES notifications(id),
    recipient_id VARCHAR(120) NOT NULL,
    recipient_address VARCHAR(320) NOT NULL,
    channel VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE,
    last_attempt_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    last_failure_type VARCHAR(50),
    last_error VARCHAR(500),
    CONSTRAINT uq_notification_delivery UNIQUE(notification_id, recipient_id, channel)
);
CREATE INDEX IF NOT EXISTS ix_delivery_queue ON deliveries(status, next_attempt_at);

CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id VARCHAR(36) REFERENCES notifications(id),
    action VARCHAR(60) NOT NULL,
    detail VARCHAR(1000) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_audit_notification ON audit_events(notification_id, occurred_at);
